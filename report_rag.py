# Step 1: Extract text from PDF
def extract_text_from_pdf(pdf_path):
    """Extract text from a PDF file."""
    logger.info(f"Starting text extraction from: {pdf_path}")
    try:
        with pdfplumber.open(pdf_path) as pdf:
            text = ""
            for page in pdf.pages:
                text += page.extract_text() + "\n"
        logger.info("Text extraction completed.")
        return text
    except Exception as e:
        logger.error(f"Error during text extraction: {e}")
        raise

# Step 2: Embed text
def embed_text(text, embedding_model):
    """Embed text using the specified embedding model."""
    logger.info("Starting text embedding.")
    try:
        text_splitter = RecursiveCharacterTextSplitter(chunk_size=500, chunk_overlap=50)
        chunks = text_splitter.split_text(text)
        embeddings = embedding_model.embed_documents(chunks)
        logger.info("Text embedding completed.")
        return chunks, embeddings
    except Exception as e:
        logger.error(f"Error during text embedding: {e}")
        raise

# Step 3: Store embeddings in Chroma
def store_embeddings(chunks, embeddings, persist_directory="chroma_db"):
    """Store embeddings in Chroma vector store."""
    logger.info("Starting to store embeddings in Chroma.")
    try:
        vector_store = Chroma.from_texts(
            texts=chunks,
            embedding=embedding_model,
            persist_directory=persist_directory
        )
        vector_store.persist()
        logger.info("Embeddings successfully stored in Chroma.")
        return vector_store
    except Exception as e:
        logger.error(f"Error during storing embeddings: {e}")
        raise

# Step 4: Query the Vector Store
def query_vector_store(query, vector_store, chat_model):
    """Query the vector store and generate a response."""
    logger.info("Starting query to the vector store.")
    try:
        retriever = vector_store.as_retriever()
        relevant_docs = retriever.get_relevant_documents(query)
        context = "\n".join([doc.page_content for doc in relevant_docs])

        prompt = PromptTemplate(
            input_variables=["context", "query"],
            template="Given the following context, answer the user's query:\n\nContext:\n{context}\n\nQuery:\n{query}"
        )
        formatted_prompt = prompt.format(context=context, query=query)
        response = chat_model.predict(formatted_prompt)
        logger.info("Query successfully processed.")
        return response
    except Exception as e:
        logger.error(f"Error during query processing: {e}")
        raise

